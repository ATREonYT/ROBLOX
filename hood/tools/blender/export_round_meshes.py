"""export_round_meshes.py (Oct 28, the owner: "keep the form, I mean just make them visibly look a bit better"): the two
small meshes that round off the shoes' blocks and wedges in game (Shared/RoundMesh, ShoeModels):

  RoundBox    a block (a Part) with its edges and corners rounded, size 1, centred, in the Part's own axes
  RoundWedge  a WedgePart (full height at +Z, sloping down to the bottom edge at -Z) rounded the same way

A shoe piece keeps its place, size and colour; only its sharp edges go soft. The rounding is a share of each side
(Bevel below), so a thin skin keeps a crisp face and a chunky block gets a soft cartoon edge.
Writes hood/src/ReplicatedStorage/Shared/Models/RoundMeshData.lua (packed for the game) and
hood/art/models/round/<Name>.obj (the same meshes for the offline renderer, render14).

Usage (Blender as a Python module; from the repo root): python3 hood/tools/blender/export_round_meshes.py
"""
import base64
import math
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import bpy  # noqa: E402
import bmesh  # noqa: E402

import hdkit as K  # noqa: E402

HOOD = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT_LUA = os.path.join(HOOD, 'src', 'ReplicatedStorage', 'Shared', 'Models', 'RoundMeshData.lua')
OUT_OBJ = os.path.join(HOOD, 'art', 'models', 'round')
BEVEL = {'RoundBox': 0.14, 'RoundWedge': 0.12}  # the rounding, as a share of the unit side
SEGMENTS = 2  # (light: a worn pair has about 90 rounded pieces)


def unit_mesh(name, geo, r):
	v, f = geo(0.5, 0.5, 0.5)
	me = bpy.data.meshes.new(name)
	me.from_pydata(v, [], f)
	me.update()
	ob = bpy.data.objects.new(name, me)
	bpy.context.scene.collection.objects.link(ob)
	m = ob.modifiers.new('bev', 'BEVEL')
	m.width = r
	m.segments = SEGMENTS
	m.profile = 0.5
	m.limit_method = 'ANGLE'
	m.angle_limit = math.radians(30)
	m.harden_normals = True
	m.use_clamp_overlap = True
	dg = bpy.context.evaluated_depsgraph_get()
	ev = ob.evaluated_get(dg)
	bm = bmesh.new()
	bm.from_mesh(ev.to_mesh())
	ev.to_mesh_clear()
	bmesh.ops.recalc_face_normals(bm, faces=bm.faces)
	bmesh.ops.triangulate(bm, faces=bm.faces)
	out = bpy.data.meshes.new(name + '_t')
	bm.to_mesh(out)
	bm.free()
	for p in out.polygons:
		p.use_smooth = True
	out.set_sharp_from_angle(angle=math.radians(35))
	return out


def arrays(me):
	"""(verts, normals, tris): corner normals deduplicated; tris (v0, v1, v2, n0, n1, n2), counter-clockwise outside."""
	verts = [tuple(v.co) for v in me.vertices]
	normals, nidx, tris = [], {}, []
	cn = me.corner_normals
	for p in me.polygons:
		ids = []
		for li in p.loop_indices:
			n = tuple(cn[li].vector)
			key = tuple(round(c, 3) for c in n)
			if key not in nidx:
				nidx[key] = len(normals)
				normals.append(n)
			ids.append((me.loops[li].vertex_index, nidx[key]))
		(a, na), (b, nb), (c, nc) = ids
		tris.append((a, b, c, na, nb, nc))
	return verts, normals, tris


def pack(verts, normals, tris):
	lo = [min(v[i] for v in verts) for i in range(3)]
	hi = [max(v[i] for v in verts) for i in range(3)]
	centre = [(lo[i] + hi[i]) / 2 for i in range(3)]
	size = [max(hi[i] - lo[i], 1e-4) for i in range(3)]
	vb = bytearray()
	for v in verts:
		for i in range(3):
			vb += struct.pack('<h', max(-32767, min(32767, round((v[i] - centre[i]) / (size[i] / 2) * 32767))))
	nb = bytearray()
	for n in normals:
		for i in range(3):
			nb += struct.pack('<b', max(-127, min(127, round(n[i] * 127))))
	tb = bytearray()
	for t in tris:
		tb += struct.pack('<6H', *t)
	return dict(Size=size, Verts=len(verts), Normals=len(normals), Tris=len(tris),
		V=base64.b64encode(bytes(vb)).decode(), N=base64.b64encode(bytes(nb)).decode(), T=base64.b64encode(bytes(tb)).decode())


def write_obj(path, verts, normals, tris):
	with open(path, 'w') as f:
		f.write('# %s: generated by export_round_meshes.py (Roblox axes, size 1)\n' % os.path.basename(path))
		for v in verts:
			f.write('v %.5f %.5f %.5f\n' % v)
		for n in normals:
			f.write('vn %.4f %.4f %.4f\n' % n)
		for t in tris:
			f.write('f %d//%d %d//%d %d//%d\n' % (t[0] + 1, t[3] + 1, t[1] + 1, t[4] + 1, t[2] + 1, t[5] + 1))


def main():
	K.reset(64, 1)
	os.makedirs(OUT_OBJ, exist_ok=True)
	packed = {}
	for name, geo in (('RoundBox', K._box_geo), ('RoundWedge', K._wedge_geo)):
		verts, normals, tris = arrays(unit_mesh(name, geo, BEVEL[name]))
		packed[name] = pack(verts, normals, tris)
		write_obj(os.path.join(OUT_OBJ, name + '.obj'), verts, normals, tris)
		print('%-10s %4d tris %4d verts' % (name, len(tris), len(verts)), flush=True)
	L = ['-- GENERATED by hood/tools/blender/export_round_meshes.py: do not edit by hand.',
		'-- The meshes that round off the shoes\' blocks and wedges (Shared/RoundMesh): size 1, centred, in a Part\'s own axes',
		'-- (RoundWedge: full height at +Z, sloping down to the bottom edge at -Z, like a WedgePart).',
		'--   [name] = { Size, Verts, Normals, Tris, V, N, T }: base64 little-endian V int16 xyz in half sizes, N int8 xyz (/127),',
		'--            T uint16 (v0 v1 v2 n0 n1 n2), 0-based',
		'return {']
	for name, p in packed.items():
		L.append('\t%s = {' % name)
		L.append('\t\tSize = { %s }, Verts = %d, Normals = %d, Tris = %d,' % (', '.join('%.5f' % c for c in p['Size']), p['Verts'], p['Normals'], p['Tris']))
		for key in ('V', 'N', 'T'):
			L.append("\t\t%s = '%s'," % (key, p[key]))
		L.append('\t},')
	L.append('}')
	open(OUT_LUA, 'w').write('\n'.join(L) + '\n')
	print('wrote', OUT_LUA, os.path.getsize(OUT_LUA), 'bytes', flush=True)


if __name__ == '__main__':
	main()
