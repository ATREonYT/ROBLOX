"""Write the World 1 shoes and shoe boxes (brief 30) from their BoxKit models as part data the game builds:

  hood/src/ReplicatedStorage/Shared/Models/ShoeParts.lua   models/shoes.py   the 22 World 1 shoes (the right shoe, foot space)
  hood/src/ReplicatedStorage/Shared/Models/BoxParts.lua    models/chests.py  the 5 chests (body, hinged lid, topper)

Plain Python (no Blender needed):  python3 hood/tools/blender/export_wear.py
ShoeModels.lua and BoxModels.lua (hand-written) build these rows into Parts and keep their public functions, so every
caller (the worn pair, followers, viewports, the reveal, the hall's dais) gets the new models unchanged.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

import boxkit as bk  # noqa: E402
from models import chests, shoes  # noqa: E402
from export_luau import num, vec  # noqa: E402

HOOD = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT_DIR = os.path.join(HOOD, 'src', 'ReplicatedStorage', 'Shared', 'Models')
SHAPE = {'Block': 'B', 'Wedge': 'W', 'Cylinder': 'C', 'Ball': 'S'}
KINDS = list(bk.KINDS)
SHOE_MAX = 60
BOX_MAX = 140


class Tables:
	def __init__(self):
		self.colors, self.rots = {}, {}

	def color(self, c):
		return self.colors.setdefault(tuple(c), len(self.colors) + 1)

	def rot(self, r):
		key = tuple(round(v, 5) for row in r for v in row)
		if all(abs(key[i] - (1 if i in (0, 4, 8) else 0)) < 1e-6 for i in range(9)):
			return 1
		return self.rots.setdefault(key, len(self.rots) + 2)

	def lua(self):
		cols = '\n'.join('\tColor3.fromRGB(%d, %d, %d),' % c for c, _ in sorted(self.colors.items(), key=lambda kv: kv[1]))
		rots = '\t{ 1, 0, 0, 0, 1, 0, 0, 0, 1 },\n' + '\n'.join('\t{ %s },' % ', '.join(num(v) for v in r) for r, _ in sorted(self.rots.items(), key=lambda kv: kv[1]))
		return 'M.Colors = {\n%s\n}\n-- rotation matrices (row-major, as CFrame.new(x, y, z, r00 .. r22)); 1 = none\nM.Rots = {\n%s\n}\n' % (cols, rots)


def rows(m, t, extra):
	out = []
	for p in m.roblox_parts():
		shape = 'E' if p.get('mesh') == 'Sphere' else SHAPE[p['shape']]
		vals = ["'%s'" % shape, str(t.color(p['color'])), str(KINDS.index(p['mat']) + 1),
			num(p['size'][0]), num(p['size'][1]), num(p['size'][2]), num(p['pos'][0]), num(p['pos'][1]), num(p['pos'][2]),
			str(t.rot(p['rot'])), "'%s'" % (p['name'] or 'Part')]
		flag = extra(p)
		if flag:
			vals.append(flag)
		out.append('{ ' + ', '.join(vals) + ' }')
	return out


HEAD = '''-- GENERATED by hood/tools/blender/export_wear.py from hood/tools/blender/models/%s.py. Do not edit by hand: change
-- the model code, then re-run the exporter (see .claude/skills/blender-roblox-models). The parts here are exactly the
-- BoxKit primitives the Blender renders and the UI pictures were made from.
%s
-- A row: { shape, colour, kind, size x, y, z, position x, y, z, rotation, name[, flags] }
--   shape  'B' block, 'W' wedge, 'C' cylinder (along its X), 'S' ball, 'E' ellipsoid (a Block with a Sphere SpecialMesh)
--   colour an index into M.Colors; kind an index into M.Kinds (BoxKit's material kinds); rotation an index into M.Rots
local M = {}
M.Kinds = { %s }
'''


def export_shoes():
	t = Tables()
	blocks, metas, problems = [], [], []
	for id in shoes.ORDER:
		m = shoes.build(id)
		problems += bk.lint(m)

		def flag(p):
			tag = p.get('tag') or {}
			if tag.get('text'):
				c = tag['text']['centre']
				return "{ text = { '%s', %s, %s, %s } }" % (tag['text']['face'], num(c[0]), num(c[1]), num(c[2]))
			if tag.get('shaft'):
				return '{ shaft = true }'
			return None
		r = rows(m, t, flag)
		if len(r) > SHOE_MAX:
			raise SystemExit('%s has %d parts (limit %d)' % (id, len(r), SHOE_MAX))
		blocks.append('\t%s = {\n%s\n\t},' % (id, '\n'.join('\t\t' + x + ',' for x in r)))
		lo, hi = m.bounds()
		metas.append("\t%s = { Name = '%s', Box = '%s', Parts = %d, Min = %s, Max = %s }," % (id, shoes.DEFS[id]['Name'], shoes.DEFS[id]['Box'], len(r), vec(lo), vec(hi)))
	what = ('-- The 22 World 1 shoes, rebuilt from the user\'s render sheets (brief 30): the RIGHT shoe in foot space (studs at\n'
		'-- scale 1, ground y = 0, the R15 foot\'s centre at x = z = 0, the outer side +X, the toe -Z). ShoeModels mirrors it\n'
		'-- for the left shoe. flags: shaft = rides the lower leg when worn (the tongue and what sits on it); text = { face,\n'
		'-- centre } a side mark the left shoe shows unmirrored, turned about its centre.')
	text = HEAD % ('shoes', what, ', '.join("'%s'" % k for k in KINDS))
	text += t.lua()
	text += 'M.Ids = { %s }\n' % ', '.join("'%s'" % i for i in shoes.ORDER)
	text += 'M.Meta = {\n%s\n}\n' % '\n'.join(metas)
	text += 'M.Shoes = {\n%s\n}\nreturn M\n' % '\n'.join(blocks)
	path = os.path.join(OUT_DIR, 'ShoeParts.lua')
	open(path, 'w').write(text)
	print('ShoeParts.lua', len(text), 'bytes', [(id, shoes.build(id).part_count()) for id in shoes.ORDER])
	return problems


def export_chests():
	t = Tables()
	blocks, problems = [], []
	G = {'body': 'b', 'lid': 'l', 'topper': 't'}
	for id in chests.ORDER:
		m = chests.build(id)
		problems += bk.lint(m)

		def flag(p):
			g = (p.get('tag') or {}).get('group', 'body')
			return "'%s'" % G[g]
		r = rows(m, t, flag)
		if len(r) + 1 > BOX_MAX:
			raise SystemExit('%s has %d parts (limit %d)' % (id, len(r) + 1, BOX_MAX))
		seal = m.meta['seal']
		lo, hi = m.bounds()
		blocks.append("\t%s = {\n\t\tName = '%s', Seal = { Body = %s, Lid = %s, Low = %s, Top = %s }, Min = %s, Max = %s,\n\t\tParts = {\n%s\n\t\t},\n\t}," % (
			id, m.name, num(seal['body']), num(seal['lid']), num(seal['low']), num(seal['top']), vec(lo), vec(hi), '\n'.join('\t\t\t' + x + ',' for x in r)))
	what = ('-- The World 1 shoe boxes as chests with hinged lids, rebuilt from the user\'s render sheets (brief 30): Street,\n'
		'-- Graffiti, Exclusive (shown as the Chrome Box), Grail (shown as the Crown Box) and the Grail Bundle\'s box. Box space:\n'
		'-- studs at scale 1, standing on y = 0, centred on x = z = 0, the front toward -Z. The last field of a row is its\n'
		'-- group: \'b\' the tub, \'l\' the lid, \'t\' the topper on the lid (the handle). The lid swings about M.Hinge (the\n'
		'-- tub\'s back top edge). Seal: where the reveal\'s seal tape lies (the tub\'s and the lid\'s front faces in the middle,\n'
		'-- how low the tape starts, the lid\'s top at the front).')
	text = HEAD % ('chests', what, ', '.join("'%s'" % k for k in KINDS))
	text += t.lua()
	text += 'M.Size = { W = %s, D = %s, Body = %s, Top = %s }\n' % (num(chests.W), num(chests.D), num(chests.BODY), num(chests.TOP))
	text += 'M.Hinge = %s\n' % vec(chests.HINGE)
	text += 'M.Ids = { %s }\n' % ', '.join("'%s'" % i for i in chests.ORDER)
	text += 'M.Boxes = {\n%s\n}\nreturn M\n' % '\n'.join(blocks)
	path = os.path.join(OUT_DIR, 'BoxParts.lua')
	open(path, 'w').write(text)
	print('BoxParts.lua', len(text), 'bytes', [(id, chests.build(id).part_count() + 1) for id in chests.ORDER])
	return problems


def main():
	os.makedirs(OUT_DIR, exist_ok=True)
	problems = export_shoes() + export_chests()
	for p in problems:
		print('lint:', p)
	return 1 if problems else 0


if __name__ == '__main__':
	sys.exit(main())
