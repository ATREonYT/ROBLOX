# pack_images.py: packs the game's pictures into Luau modules, so the game draws them itself (Shared/ImageLoader, with
# EditableImage) and nothing has to be uploaded first. Ported from the owner's Huzz Valley (tools/icons/pack_images.py),
# with a smaller format: each picture is a palette of up to 256 RGBA colours (dithered) and its pixels as runs of
# (count, colour index) bytes, so the 200 pictures weigh ~2.5 MB of text instead of ~20 MB.
#   hood/art/icons3d/<Name>.png  -> Shared/Images/Icons/<Name>.lua   (items 192 px, other icons 160 px at most)
#   hood/art/ui_owner/<name>.png -> Shared/Images/Ui/<name>.lua      (the owner's UI pieces, cut_mockup.py; as cut, plus
#                                                                      Slice = { x0, y0, x1, y1 } and Mode from slices.json)
# Each module returns { W, H, P = base64 palette (RGBA, 4 bytes a colour), Data = base64 runs, Slice?, Mode? }.
# Usage (from the repo root; re-run whenever a picture changes): python3 -I hood/tools/ui/pack_images.py
import base64
import json
import os

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
HOOD = os.path.abspath(os.path.join(HERE, '..', '..'))
OUT = os.path.join(HOOD, 'src', 'ReplicatedStorage', 'Shared', 'Images')
# Items show biggest (a shoe card ~270 px wide on a PC): 192 px; HUD and window icons show at most ~150 px: 160 px.
ITEM_PREFIX, MAX_ITEM, MAX_ICON = ('Shoe_', 'Box_', 'Gun_'), 192, 160


def encode(im):
    q = im.quantize(256, method=Image.Quantize.FASTOCTREE, dither=Image.Dither.FLOYDSTEINBERG)
    pal = q.getpalette(rawmode='RGBA') or []
    used = max(q.tobytes()) + 1 if q.width * q.height else 1
    palette = bytes(pal[:used * 4]).ljust(used * 4, b'\0')
    idx = q.tobytes()
    out = bytearray()
    i, n = 0, len(idx)
    while i < n:
        v, j = idx[i], i + 1
        while j < n and j - i < 255 and idx[j] == v:
            j += 1
        out += bytes((j - i, v))
        i = j
    return base64.b64encode(palette).decode(), base64.b64encode(bytes(out)).decode()


def pack(kind, src, cap, meta=None):
    dst = os.path.join(OUT, kind)
    os.makedirs(dst, exist_ok=True)
    for f in os.listdir(dst):
        os.remove(os.path.join(dst, f))
    total = 0
    for name in sorted(os.listdir(src)):
        if not name.endswith('.png'):
            continue
        stem = name[:-4]
        im = Image.open(os.path.join(src, name)).convert('RGBA')
        limit = cap(stem)
        if limit and max(im.size) > limit:
            im.thumbnail((limit, limit), Image.LANCZOS)
        pal, data = encode(im)
        fields = 'W = %d, H = %d, P = "%s", Data = "%s"' % (im.width, im.height, pal, data)
        m = meta.get(stem) if meta else None
        if m:
            k = im.width / m['w']
            c = [round(v * k) for v in m['center']]
            fields += ', Mode = "%s", Slice = { %d, %d, %d, %d }' % (m['mode'], c[0], c[1], c[2], c[3])
        text = '-- Generated by hood/tools/ui/pack_images.py from hood/art/%s/%s. Do not edit.\nreturn { %s }\n' % (os.path.basename(src), name, fields)
        with open(os.path.join(dst, stem + '.lua'), 'w') as fh:
            fh.write(text)
        total += len(text)
    print('packed %s: %d KB' % (kind, total // 1024))


pack('Icons', os.path.join(HOOD, 'art', 'icons3d'), lambda s: MAX_ITEM if s.startswith(ITEM_PREFIX) else MAX_ICON)
with open(os.path.join(HOOD, 'art', 'ui_owner', 'slices.json')) as fh:
    SLICES = json.load(fh)
pack('Ui', os.path.join(HOOD, 'art', 'ui_owner'), lambda s: None, SLICES)
