-- (Oct 28, the feel round) The fight's weight and payoff (Shared/FightJuice) and the owner's fight moves
-- (Config/Animations Punch and Kick, CharMotion.melee's drawn stand-in).
return function(t)
	local RS = game:GetService('ReplicatedStorage')
	local FJ = require(RS.Shared.FightJuice)
	local AR = require(RS.Shared.AnimationRules)
	local Anim = require(RS.Shared.Config.Animations)
	local CharMotion = require(RS.Shared.CharMotion)

	t.test('hit-stop: none on a shot, a beat on a swing, the longest on a knock-out, all short', function()
		t.expect.equal(FJ.hitStop('Shot'), 0)
		t.expect.equal(FJ.hitStop(nil), 0)
		t.expect.truthy(FJ.hitStop('Melee') > 0 and FJ.hitStop('Melee') < FJ.hitStop('KO'))
		t.expect.truthy(FJ.hitStop('KO') <= FJ.hitStop('KOMelee'))
		t.expect.truthy(FJ.hitStop('KOMelee') <= 0.12) -- (a few frames: never a stall)
	end)

	t.test('the squash: full at the hit, one small stretch, gone by SquashTime', function()
		t.expect.equal(FJ.squash(0), 1)
		t.expect.equal(FJ.squash(FJ.SquashTime), 0)
		t.expect.equal(FJ.squash(-1), 0)
		t.expect.equal(FJ.squash('x'), 0)
		local lo = 1
		for k = 0, 40 do lo = math.min(lo, FJ.squash(FJ.SquashTime * k / 40)) end
		t.expect.truthy(lo < 0 and lo > -0.3) -- (a stretch past rest, small)
	end)

	t.test('the knock-out bounce: one hop then a smaller one, on the ground after', function()
		t.expect.equal(FJ.bounce(0), 0)
		t.expect.equal(FJ.bounce(FJ.BounceTime), 0)
		t.expect.equal(FJ.bounce(-0.1), 0)
		local first = FJ.bounce(FJ.BounceTime * 0.65 / 2)
		local second = FJ.bounce(FJ.BounceTime * (0.65 + 0.35 / 2))
		t.expect.truthy(math.abs(first - FJ.BounceHeight) < 1e-6)
		t.expect.truthy(second > 0 and second < first / 2)
	end)

	t.test('the streak: knock-outs each within StreakGap of the last; it ends when the gap runs out', function()
		local g = FJ.StreakGap
		t.expect.equal(FJ.streak({}, 0), 0)
		t.expect.equal(FJ.streak({ 10 }, 10), 1)
		t.expect.equal(FJ.streak({ 10, 11, 12 }, 12), 3)
		t.expect.equal(FJ.streak({ 1, 10, 11 }, 11), 2) -- (an old one doesn't count)
		t.expect.equal(FJ.streak({ 10, 11 }, 11 + g + 0.1), 0) -- (over)
		t.expect.equal(FJ.orbCount(1), 3)
		t.expect.equal(FJ.orbCount(3), 5)
		t.expect.equal(FJ.orbCount(40), 7) -- (never a flood)
	end)

	t.test('a world point on the screen: the centre ahead, left is left, up is up, behind is nothing', function()
		local cam = CFrame.lookAt(Vector3.new(0, 0, 0), Vector3.new(0, 0, -10))
		local size = Vector2.new(1280, 720)
		local p = FJ.project(cam, 70, size, Vector3.new(0, 0, -10))
		t.expect.truthy(math.abs(p.X - 640) < 1e-6 and math.abs(p.Y - 360) < 1e-6)
		local l = FJ.project(cam, 70, size, Vector3.new(-2, 2, -10))
		t.expect.truthy(l.X < 640 and l.Y < 360)
		t.expect.equal(FJ.project(cam, 70, size, Vector3.new(0, 0, 5)), nil)
		-- (the top of the view is half the field of view up)
		local top = FJ.project(cam, 70, size, Vector3.new(0, 10 * math.tan(math.rad(35)), -10))
		t.expect.truthy(math.abs(top.Y) < 1e-3)
	end)

	t.test('the camera thump is kid-comfortable: a few degrees at most', function()
		t.expect.truthy(FJ.MaxFov > 0 and FJ.MaxFov <= 4)
	end)

	t.test('fight moves: Punch and Kick have slots in Config/Animations, empty until the owner uploads them', function()
		t.expect.equal(type(Anim.Punch), 'string')
		t.expect.equal(type(Anim.Kick), 'string')
		t.expect.equal(AR.moveId('Punch', { Punch = '' }), nil)
		t.expect.equal(AR.moveId('Kick', { Kick = 123 }), 'rbxassetid://123')
		t.expect.equal(AR.oneShot(nil, 'Punch', { Punch = 123 }), nil) -- (no animator: nothing)
		-- swings go Punch, Punch, Kick in turn
		t.expect.equal(CharMotion.meleeMove(1), 'Punch')
		t.expect.equal(CharMotion.meleeMove(2), 'Punch')
		t.expect.equal(CharMotion.meleeMove(3), 'Kick')
		t.expect.equal(CharMotion.meleeMove(4), 'Punch')
	end)

	t.test('without an id the drawn swing stands in (no character: still a swing)', function()
		t.expect.equal(CharMotion.melee(1), 'Drawn')
		local pose, w = CharMotion.swingPose(0.12, 1)
		t.expect.truthy(type(pose) == 'table' and w > 0)
	end)
end
