return function(t)
	local B = require(game.ReplicatedStorage.Shared.BigAttr)
	local R = require(game.ReplicatedStorage.Shared.StageRules)
	t.test('small numbers stay numbers; big whole ones are kept as digits', function()
		t.expect.equal(B.encode(220000), 220000)
		t.expect.equal(B.encode(2147483647), 2147483647)
		t.expect.equal(B.encode(2150000000), '2150000000')
		t.expect.equal(B.encode(13000000000), '13000000000')
		t.expect.equal(B.encode(2.5e9 + 0.5), 2.5e9 + 0.5)
		t.expect.equal(B.encode('x'), 'x')
	end)
	t.test('a stored value reads back as the same number', function()
		for _, n in { 10, 2150000000, 13000000000, 5e14 } do t.expect.equal(B.decode(B.encode(n)), n) end
		t.expect.equal(B.decode(nil), nil)
	end)
	t.test("a gate's billions-high Required reads back through StageRules", function()
		local m = Instance.new('Model')
		m:SetAttribute('Stage', 4)
		m:SetAttribute('WallId', 'HoodW2Stage4')
		m:SetAttribute('LineZ', -192)
		B.set(m, 'Required', 2150000000)
		local g = R.fromModels({ m })
		t.expect.equal(g[1].Required, 2150000000)
	end)
end
