--!strict
--[[
	EnemyLooks: the stage enemies as real Roblox avatars (blocky R15 + real catalog clothing and accessories).

	Every look lives in the EnemyRoster module next to this one (generated by generator/make_roster.py).
	Each enemy wears real catalog items: classic Shirt + Pants, hair, hats, glasses, chains, bags and an official
	Roblox classic-face head. Roblox loads them through a HumanoidDescription, so nothing is hand-made.

	Server API
	  EnemyLooks.forStage(stage)     -> { crew, minions = {key, key, key}, boss = key? }  who stands in a stage
	  EnemyLooks.build(key, cframe?) -> Model                                            a new R15 enemy
	  EnemyLooks.dress(model, key)   -> boolean                                          re-dress an existing R15 rig
	  EnemyLooks.info(key)           -> Entry?                                           name, crew, role, scale

	The 1st stage of a crew is the 3 minions; the 2nd stage is the same 3 minions + their boss.
	Bosses are grown with Model:ScaleTo (x1.5, the final boss x1.6), so clothes and accessories scale with them.

	Catalog items can be deleted or moderated by their creators. If a look fails to load, the enemy falls back to
	skin + shirt/pants only, then to plain skin, and warns in the output, so a stage never ends up empty.
]]

local Players = game:GetService("Players")

-- (Oct 27) World 2's place (Business District) dresses its crews from World2Roster: the office workers, up to the CEO.
local okWorld, WorldInfo = pcall(function() return require(game:GetService("ReplicatedStorage").Shared.WorldInfo) end)
local inWorld2 = okWorld and WorldInfo.current() == 2 and script.Parent:FindFirstChild("World2Roster") ~= nil
local Roster = require(script.Parent:WaitForChild(if inWorld2 then "World2Roster" else "EnemyRoster"))

export type Item = { id: number, type: string }
export type Entry = {
	key: string,
	crew: string,
	role: string,
	name: string,
	shirt: number,
	pants: number,
	tshirt: number,
	head: number,
	headParts: { Item },
	accessories: { Item },
	skin: Color3,
	scale: number,
}

local EnemyLooks = {}

local byKey: { [string]: Entry } = {}
for _, crew in ipairs(Roster.Crews) do
	for _, c in ipairs(crew.Characters) do
		byKey[c.key] = c
	end
end

local ACCESSORY_TYPE: { [string]: Enum.AccessoryType } = {
	Hat = Enum.AccessoryType.Hat,
	Hair = Enum.AccessoryType.Hair,
	Face = Enum.AccessoryType.Face,
	Neck = Enum.AccessoryType.Neck,
	Shoulder = Enum.AccessoryType.Shoulder,
	Front = Enum.AccessoryType.Front,
	Back = Enum.AccessoryType.Back,
	Waist = Enum.AccessoryType.Waist,
	Eyebrow = Enum.AccessoryType.Eyebrow,
	Eyelash = Enum.AccessoryType.Eyelash,
}

-- level 3 = the full look, 2 = skin + classic clothes, 1 = skin only (fallbacks when catalog items fail to load)
local function describe(e: Entry, level: number): HumanoidDescription
	local d = Instance.new("HumanoidDescription")
	d.HeadColor = e.skin
	d.TorsoColor = e.skin
	d.LeftArmColor = e.skin
	d.RightArmColor = e.skin
	d.LeftLegColor = e.skin
	d.RightLegColor = e.skin
	-- the blocky R15 body: default body parts, classic proportions
	d.BodyTypeScale = 0
	d.ProportionScale = 0
	if level >= 2 then
		d.Shirt = e.shirt
		d.Pants = e.pants
		d.GraphicTShirt = e.tshirt
	end
	if level >= 3 then
		d.Head = e.head
		local list = {}
		for _, a in ipairs(e.accessories) do
			table.insert(list, { AssetId = a.id, AccessoryType = ACCESSORY_TYPE[a.type], IsLayered = false })
		end
		for _, p in ipairs(e.headParts) do
			if p.type == "Mood" then
				d.MoodAnimation = p.id
			else
				table.insert(list, { AssetId = p.id, AccessoryType = ACCESSORY_TYPE[p.type], IsLayered = false })
			end
		end
		d:SetAccessories(list, true)
	end
	return d
end

local function tag(model: Model, e: Entry)
	model:SetAttribute("EnemyKey", e.key)
	model:SetAttribute("EnemyCrew", e.crew)
	model:SetAttribute("EnemyRole", e.role)
	model:ScaleTo(e.scale) -- absolute, so dressing a rig twice never stacks
end

function EnemyLooks.info(key: string): Entry?
	return byKey[key]
end

function EnemyLooks.forStage(stage: number): { crew: string, minions: { string }, boss: string? }
	for _, crew in ipairs(Roster.Crews) do
		local first, second = crew.Stages[1], crew.Stages[2]
		if stage == first or stage == second then
			local minions: { string }, boss: string? = {}, nil
			for _, c in ipairs(crew.Characters) do
				if c.role == "boss" then
					boss = c.key
				else
					table.insert(minions, c.key)
				end
			end
			return { crew = crew.Name, minions = minions, boss = if stage == second then boss else nil }
		end
	end
	error("EnemyLooks.forStage: no crew for stage " .. tostring(stage))
end

function EnemyLooks.build(key: string, cframe: CFrame?): Model
	local e = byKey[key]
	assert(e, "EnemyLooks.build: unknown enemy " .. key)
	for level = 3, 1, -1 do
		local ok, result = pcall(Players.CreateHumanoidModelFromDescriptionAsync, Players, describe(e, level), Enum.HumanoidRigType.R15)
		if ok then
			if level < 3 then
				warn(("EnemyLooks: %s is missing some catalog items (fallback level %d)"):format(key, level))
			end
			local model = result :: Model
			model.Name = e.name
			local hum = model:FindFirstChildOfClass("Humanoid")
			if hum then
				hum.DisplayDistanceType = Enum.HumanoidDisplayDistanceType.None -- the game draws its own name and health bars
				hum.BreakJointsOnDeath = false
			end
			-- the default Animate LocalScript never runs on a server NPC; the game animates its enemies itself
			local animate = model:FindFirstChild("Animate")
			if animate then
				animate:Destroy()
			end
			tag(model, e)
			if cframe then
				model:PivotTo(cframe)
			end
			return model
		end
	end
	error("EnemyLooks.build: could not create " .. key)
end

function EnemyLooks.dress(model: Model, key: string): boolean
	local e = byKey[key]
	assert(e, "EnemyLooks.dress: unknown enemy " .. key)
	local hum = model:FindFirstChildOfClass("Humanoid")
	if not hum or hum.RigType ~= Enum.HumanoidRigType.R15 then
		warn("EnemyLooks.dress: " .. model:GetFullName() .. " is not an R15 rig")
		return false
	end
	for level = 3, 1, -1 do
		if pcall(hum.ApplyDescriptionResetAsync, hum, describe(e, level)) then
			tag(model, e)
			return true
		end
	end
	return false
end

return EnemyLooks
