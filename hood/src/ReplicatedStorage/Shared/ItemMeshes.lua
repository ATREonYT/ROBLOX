-- ItemMeshes: the user's blocky designs as real 3D meshes (brief 32; brief 31 MESH made the first version), imported
-- ONCE by the user into ReplicatedStorage.HoodItemMeshes (hood/art/MESH_IMPORT.md: four .glb files and one command-bar
-- script). Each item is a Model named by its id holding MeshParts: `<Id>`, `<Id>_2` ... (palette-textured bodies) and
-- `<Id>_Glow_<hex>` (Neon), plus invisible `Collider` boxes for walk-through items (the gate), and the attributes
-- DesignMin / DesignMax (its bounds in design studs), Collision ('solid' / 'prop' / 'gun') and Muzzle (guns). When the
-- folder or the item is missing (no import yet, the unit tests, the offline harness), every caller keeps its Part build:
-- nothing needs the meshes. (Brief 31's items, Box_<Id> with a `Lid` and parts named <Group>_<Material>_<hex>, still work.)
--
--   ItemMeshes.has(id) -> boolean
--   ItemMeshes.place(id, cf, size?, parent, fallbackFn, opts?) -> (Model?, usedMesh: boolean)
--       the item's mesh with its BOTTOM CENTRE at cf (front toward cf's -Z), scaled by the fitting rule:
--         size = a Vector3: the largest that fits inside that box, proportions kept;
--         size = a number: its largest side becomes that many studs;
--         size = nil: the design size (the user's studs);
--       opts.center = true anchors its centre at cf instead. Without a mesh it returns fallbackFn(cf, size, parent)
--       (and false), so the Part build is the fallback.
--   ItemMeshes.fit(id, size?) -> (scale, fitted size: Vector3)   the same rule from the design size; works without the
--       import (for fallbacks that should take the same room)
--   ItemMeshes.size(id) -> Vector3?             the design size in studs (ItemMeshes.Design, or the import's)
--   ItemMeshes.muzzle(id) -> Vector3?           a gun's muzzle point in design studs (the grip is the origin)
--   ItemMeshes.build(id, cf, scale) -> Model?   the mesh in its DESIGN frame: the design origin (bottom centre; a gun's
--       grip) at cf, design studs times `scale`; nil without a mesh (GunModels, BoxModels and ShoeModels use this)
--   ItemMeshes.bounds(id) -> (min, max)?        its design bounds (needs the import)
--   ItemMeshes.Alias[id] = the id to use (other names callers may ask for)
--   ItemMeshes.Design[id] = { Min, Max, Collision, Muzzle? }   every packaged id (generated from manifest.json)
--   ItemMeshes.root                              tests may set a Folder here in place of ReplicatedStorage's
-- Every part comes back Anchored. Bodies keep their palette texture; `_Glow_<hex>` parts are Neon in that colour (from
-- the name, so an import that skipped the setup script still glows). Collision follows the item's class: 'solid' items
-- (big things players walk into, the slabs they stand on) collide, through their Colliders when they have some;
-- everything else has CanCollide, CanTouch and CanQuery off. No asset ids live in code.
