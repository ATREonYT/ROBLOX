"""Writes apply_hub_layout.lua (Studio Command Bar script) from hub_layout.json + studio_colors."""
import json
d = json.load(open("hub_layout.json"))
# Part colours for Studio: the reference's lit colours, corrected for our lighting
# (measured lit/part ratios in Studio, Nov 8). Rerun after changing STUDIO_COLORS.
STUDIO = json.load(open("studio_colors.json"))
def col(k): return STUDIO.get(k, d["ref_colors"].get(k, k))
L = ["-- [HubMap] generated by make_apply_lua.py from hub_layout.json. Paste into Studio's Command Bar.",
     "-- Backs up the old hub to ServerStorage.MapBackup_Nov8_Layout first (run once), then rebuilds Map.Hub.",
     "local P = {"]
for p in d["parts"]:
    if p.get("preview_only"): continue
    L.append('{g=%r,n=%r,p={%g,%g,%g},s={%g,%g,%g},c="%s",m="%s",t=%g,cc=%s,low=%s},' % (
        p["group"], p["name"], *p["pos"], *p["size"], col(p["color"]), p["material"],
        p.get("transparency", 0), "false" if p.get("collide") is False else "true",
        json.dumps(p["low"]) if p.get("kind") == "Wedge" else "nil"))
L.append("}")
def lua(v):
    if v is None: return "nil"
    if isinstance(v, str): return json.dumps(v)
    if isinstance(v, (int, float)): return repr(v)
    if isinstance(v, list): return "{" + ", ".join(lua(x) for x in v) + "}"
    return "{" + ", ".join("[%s]=%s" % (json.dumps(k), lua(x)) for k, x in v.items()) + "}"
L.append("local MOVES = " + lua(d["moves"]))
L.append("local SHOP = {pos={%g,%g,%g}, size={%g,%g,%g}}" % (*d["shopzone"]["pos"], *d["shopzone"]["size"]))
L.append("local RECOLOR = " + lua({k: col(k) for k in ["stone", "stone_dark"]}))
L.append(open("apply_hub_layout.body.lua").read())
open("apply_hub_layout.lua", "w").write("\n".join(L))
print("ok", sum(1 for p in d["parts"] if not p.get("preview_only")), "parts")
