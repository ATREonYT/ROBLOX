# Bakes the 5 Game Pass knives of design/knives/gamepass/Gamepass_Knives.glb (the owner's file, as it is: every
# triangle, every colour) into src/ReplicatedStorage/Shared/KnifeGlb/<Key>_<n>.lua, so the game can draw them as his
# model while his own import of that file isn't in ServerStorage/HuzzKnives yet (Gameplay/KnifeDress builds them on
# each screen with Roblox's EditableMesh).
# Each knife's triangles are grouped by look (colour, glow, blade or not, material): one MeshPart per group (a big
# group in a few: CHUNK triangles each). Each file: { key, col (rrggbb), glow, mat / refl (the Roblox material and
# Reflectance nearest the .glb's metallic and roughness: glb_material, the same rule as Shared/KnifeLook.glbMaterial),
# blade, nv / nt (vertices / triangles),
# lo / hi (its box in the Handle's space, studs), v, t }. Positions are in the game's Handle space in studs (X = the
# blade's thin way = the .glb's Z, Y = to the tip from the grip's middle, Z = minus the .glb's X; pommel to tip = the
# knife's Studs; the same frame as tools/knives/knife_boxes.py), stored in v as 16-bit steps across lo..hi (x y z per
# vertex); t holds 16-bit vertex numbers, 3 per triangle, counter-clockwise seen from outside (glTF's order; turned
# back for mirrored parts). Both base64, little-endian.
# Usage (from huzz-valley/): python3 -I tools/knives/bake_pass_meshes.py
import base64, collections, json, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
import glb
from bake_knives import gamepass_knives

OUT = 'src/ReplicatedStorage/Shared/KnifeGlb'
CHUNK = 6000  # triangles per mesh (one module): each file stays well under Studio's 200,000 characters a script
MAX_VERTS, MAX_TRIS = 60000, 20000  # Roblox's EditableMesh limits (one mesh)
HEAD = ("-- GENERATED by tools/knives/bake_pass_meshes.py from design/knives/gamepass/Gamepass_Knives.glb: don't edit.\n"
        "-- One mesh of a Game Pass knife as the owner made it (Gameplay/KnifeDress builds it; the format is in that tool).\n")


def glb_material(metal, rough, glow):
    """Shared/KnifeLook.glbMaterial in Python (tests/KnifeModels.spec checks the baked files agree with it)."""
    if glow:
        return 'Neon', 0
    if metal >= 0.5:
        return 'Metal', 0.12 if rough <= 0.35 else 0.04
    if rough >= 0.7:
        return 'Plastic', 0
    return 'SmoothPlastic', 0


def wrap(s, n=120):
    return '\n'.join(s[i:i + n] for i in range(0, len(s), n))


def main():
    knives = {k['node']: k for k in json.load(open('tools/knives/knives.json')) if k['rarity'] == 'Exclusive'}
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.lua'):
            os.remove(os.path.join(OUT, f))
    total = 0
    for node_name, prims, inv, js, binc in gamepass_knives():
        k = knives.get(node_name)
        if not k:
            continue
        per = k['studs'] / k['length']
        groups = collections.OrderedDict()
        for p in prims:
            m = inv @ p['matrix']
            flip = np.linalg.det(m[:3, :3]) < 0
            pos = (np.c_[p['local'], np.ones(len(p['local']))] @ m.T)[:, :3]
            h = np.c_[pos[:, 2], pos[:, 1] - k['grip'], -pos[:, 0]] * per  # .glb -> Handle space, studs
            idx = p['idx'][:, ::-1] if flip else p['idx']
            col = glb.texture_colour(js, binc, p['material'].get('texture')) or 'cccccc'
            glow = p['material']['name'].startswith('glow')
            blade = p['node'].lower().startswith('blade')
            mat, refl = glb_material(round(float(p['material']['metal']), 2), round(float(p['material']['rough']), 2), glow)
            g = groups.setdefault((col, glow, blade, mat, refl), {'pos': [], 'idx': [], 'n': 0})
            g['pos'].append(h)
            g['idx'].append(idx + g['n'])
            g['n'] += len(h)
        n = 0
        for (col, glow, blade, mat, refl), g in groups.items():
            allpos = np.concatenate(g['pos'])
            allidx = np.concatenate(g['idx'])
            for c0 in range(0, len(allidx), CHUNK):
                used, idx = np.unique(allidx[c0:c0 + CHUNK], return_inverse=True)  # (only the vertices it draws)
                idx = idx.reshape(-1, 3)
                pos = allpos[used]
                assert len(pos) <= MAX_VERTS and len(idx) <= MAX_TRIS, (node_name, col, len(pos), len(idx))
                lo, hi = pos.min(0), pos.max(0)
                span = np.maximum(hi - lo, 1e-6)
                q = np.round((pos - lo) / span * 65535).astype('<u2')
                v = base64.b64encode(q.tobytes()).decode()
                t = base64.b64encode(idx.astype('<u2').tobytes()).decode()
                n += 1
                path = os.path.join(OUT, '%s_%d.lua' % (k['key'], n))
                with open(path, 'w') as fh:
                    fh.write(HEAD + 'return { key = "%s", col = "%s", glow = %s, mat = "%s", refl = %g, blade = %s, nv = %d, nt = %d,\n'
                             '\tlo = { %.4f, %.4f, %.4f }, hi = { %.4f, %.4f, %.4f },\n\tv = [[\n%s]],\n\tt = [[\n%s]] }\n' % (
                                 k['key'], col, str(glow).lower(), mat, refl, str(blade).lower(), len(pos), len(idx), *lo, *hi, wrap(v), wrap(t)))
                size = os.path.getsize(path)
                assert size < 190000, (path, size)
                total += size
        tris = sum(len(np.concatenate(g['idx'])) for g in groups.values())
        print('%-16s %d looks, %d meshes, %d triangles' % (k['key'], len(groups), n, tris))
    print('%s: %d KB' % (OUT, total // 1024))


if __name__ == '__main__':
    main()
