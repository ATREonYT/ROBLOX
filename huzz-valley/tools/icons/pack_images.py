# Packs assets/icons and assets/art into Luau modules (src/ReplicatedStorage/Shared/Images/{Icons,Art}/<Name>.lua),
# so the game can draw them itself (EditableImage) without the owner uploading anything.
# The effect textures (assets/fx) go to src/ServerStorage/HuzzImages/Fx/<Name>.lua instead: only the owner's one-time
# upload helper reads them (the game uses the uploaded IDs, Shared/FxTexture), so clients never download them.
# Each module returns { W = width, H = height, Data = base64 of the raw RGBA pixels }.
# Usage (from huzz-valley/): python3 tools/icons/pack_images.py   (re-run whenever an image in assets/ changes)
import base64, os
from PIL import Image

OUT = 'src/ReplicatedStorage/Shared/Images'
# Icons show at most about 100 points, which is about 200 px on a sharp (Retina) screen, so the packed copy is shrunk
# to fit 192 px (smooth resampling): sharp there, while keeping the
# game small. The full-size files in assets/ stay as they are.
MAX_ICON = 192
# Icons from the owner's sheet that no screen uses yet: kept in assets/, not packed into the game.
UNUSED = {'arrow-next', 'play-tile', 'plus-tile', 'monitor-small', 'social-chat'}
# Effect textures keep their real size (flipbook frames need every pixel; the owner's screen is Retina), capped at
# 1024 for flipbook sheets (Shared/FxTexture.SHEETS) and 512 for single shapes.
FX_OUT = 'src/ServerStorage/HuzzImages/Fx'
FX_SHEETS = {'burst-star', 'twinkle', 'bolt', 'flame-sheet', 'shock-sheet', 'slash-sheet', 'butterfly'}
OLD_FX = os.path.join(OUT, 'Fx')  # (where they used to be packed)
if os.path.isdir(OLD_FX):
    for f in os.listdir(OLD_FX):
        os.remove(os.path.join(OLD_FX, f))
    os.rmdir(OLD_FX)


def pascal(stem):
    return ''.join(w.capitalize() for w in stem.split('-'))


for kind, src in (('Icons', 'assets/icons'), ('Art', 'assets/art'), ('Fx', 'assets/fx')):
    dst = FX_OUT if kind == 'Fx' else os.path.join(OUT, kind)
    os.makedirs(dst, exist_ok=True)
    for f in os.listdir(dst):
        os.remove(os.path.join(dst, f))
    for name in sorted(os.listdir(src)):
        if not name.endswith('.png') or name[:-4] in UNUSED:
            continue
        im = Image.open(os.path.join(src, name)).convert('RGBA')
        if kind == 'Icons' and max(im.size) > MAX_ICON:
            im.thumbnail((MAX_ICON, MAX_ICON), Image.LANCZOS)
        if kind == 'Fx':
            cap = 1024 if name[:-4] in FX_SHEETS else 512
            if max(im.size) > cap:
                im.thumbnail((cap, cap), Image.LANCZOS)
        if kind == 'Fx':
            # White shapes: only the alpha matters, and it's mostly runs of the same value, so it's packed as
            # (count, alpha) byte pairs (Mask = true); UI/ImageLoader expands it back to white RGBA pixels.
            alpha = im.getchannel('A').tobytes()
            out = bytearray()
            i, n = 0, len(alpha)
            while i < n:
                v, j = alpha[i], i + 1
                while j < n and j - i < 255 and alpha[j] == v:
                    j += 1
                out += bytes((j - i, v))
                i = j
            data = base64.b64encode(bytes(out)).decode()
            fields = 'W = %d, H = %d, Mask = true, Data = "%s"' % (im.width, im.height, data)
        else:
            data = base64.b64encode(im.tobytes()).decode()
            fields = 'W = %d, H = %d, Data = "%s"' % (im.width, im.height, data)
        with open(os.path.join(dst, pascal(name[:-4]) + '.lua'), 'w') as fh:
            fh.write('-- Generated by tools/icons/pack_images.py from %s/%s. Do not edit.\n' % (src, name))
            fh.write('return { %s }\n' % fields)
print('packed')
