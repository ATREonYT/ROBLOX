--!strict
-- Bakes the minimap's road data from the Vice Bay map into ReplicatedStorage.MTL_RoadMap (a generated ModuleScript).
-- Run in Studio's Command Bar or through the Studio MCP `execute_luau` (Edit mode), again after any road changes.
-- Why baked: the place uses StreamingEnabled, so a client can't see far road parts; the minimap reads this instead.
-- MTL_RoadMap lives outside the Rojo-mapped MTL folders (like MTL_AmbientRigs), so Rojo never deletes it.
-- Never hand-edit MTL_RoadMap. Format (all ints, studs; read by Rules/RoadGraph.lua):
--   Roads = "x z y ang L W name;..."   one flat asphalt rectangle: centre x/z, top y, long-axis angle in degrees
--                                       (atan2(dz, dx), 0..179), long side L, short side W, name = index into Names (0 = none)
--   Water = "x z ang L W;..."           flat water rectangles (river, canals) drawn under the roads
local ReplicatedStorage = game:GetService("ReplicatedStorage")

local VB = workspace:FindFirstChild("ViceBay")
assert(VB, "no Workspace.ViceBay")

-- folders that never hold drivable road (parking lots on buildings, rail beds, props)
local SKIP = { Buildings = true, Landmarks = true, Rail = true, River = true, Canal = true, Parks = true, RoadWear = true, POIs = true, Metro = true }
local WATER = { River = true, Canal = true }
local MIN_W = 14 -- narrower asphalt is patches, kerbs and paint
local MAX_Y = 90 -- roofs above this

local function flat(p: BasePart): (boolean, Vector3?, number, number, number)
	local cf, s = p.CFrame, p.Size
	local axes = { cf.RightVector, cf.UpVector, cf.LookVector }
	local sz = { s.X, s.Y, s.Z }
	local up = 0
	for i = 1, 3 do
		if math.abs(axes[i].Y) > 0.9 then
			up = i
		end
	end
	if up == 0 or sz[up] > 3 then
		return false, nil, 0, 0, 0
	end
	local h = {}
	for i = 1, 3 do
		if i ~= up then
			table.insert(h, i)
		end
	end
	local a, b = h[1], h[2]
	if sz[b] > sz[a] then
		a, b = b, a
	end
	return true, axes[a], sz[a], sz[b], sz[up]
end

local function roadName(p: Instance, top: Instance): string
	local node = p.Parent
	local best = ""
	while node and node ~= top do
		if node:IsA("Model") and node.Name ~= "Model" and node.Name ~= "StreetFurniture" then
			best = node.Name
		end
		node = node.Parent
	end
	return best
end

local names: { string } = {}
local nameIdx: { [string]: number } = {}
local roads: { string } = {}
local water: { string } = {}
local seen: { [string]: boolean } = {}

for _, folder in VB:GetChildren() do
	local isWater = WATER[folder.Name] == true
	if SKIP[folder.Name] and not isWater then
		continue
	end
	for _, p in folder:GetDescendants() do
		if not p:IsA("BasePart") or p.Position.Y > MAX_Y then
			continue
		end
		local ok, dir, L, W, T = flat(p)
		if not ok or not dir or W < MIN_W then
			continue
		end
		local ang = math.round(math.deg(math.atan2(dir.Z, dir.X)) % 180) % 180
		local x, z = math.round(p.Position.X), math.round(p.Position.Z)
		if isWater then
			local c = p.Color
			local blue = p.Material == Enum.Material.Water or p.Material == Enum.Material.Glass or c.B > c.R + 0.12
			if blue and W >= 20 then
				table.insert(water, string.format("%d %d %d %d %d", x, z, ang, math.round(L), math.round(W)))
			end
			continue
		end
		if p.Material ~= Enum.Material.Asphalt or p:GetAttribute("VBVar") == "AsphaltTarPatch" then
			continue
		end
		local y = math.round(p.Position.Y + T / 2)
		local line = string.format("%d %d %d %d %d %d", x, z, y, ang, math.round(L), math.round(W))
		if seen[line] then
			continue -- stacked duplicates (two decals on one road) draw once
		end
		seen[line] = true
		local n = roadName(p, folder)
		local idx = 0
		if n ~= "" then
			idx = nameIdx[n] or 0
			if idx == 0 then
				table.insert(names, n)
				idx = #names
				nameIdx[n] = idx
			end
		end
		table.insert(roads, line .. " " .. idx)
	end
end

local quoted = {}
for _, n in names do
	table.insert(quoted, string.format("%q", n))
end
local source = table.concat({
	"-- GENERATED by tools/BakeRoadMap.lua (" .. os.date("!%Y-%m-%d %H:%M") .. " UTC). Do not edit by hand: re-run the baker.",
	"return {",
	"\tVersion = " .. os.time() .. ",",
	"\tNames = { " .. table.concat(quoted, ", ") .. " },",
	'\tRoads = "' .. table.concat(roads, ";") .. '",',
	'\tWater = "' .. table.concat(water, ";") .. '",',
	"}",
}, "\n")

local mod = ReplicatedStorage:FindFirstChild("MTL_RoadMap")
if not mod then
	mod = Instance.new("ModuleScript")
	mod.Name = "MTL_RoadMap"
	mod.Parent = ReplicatedStorage
end
(mod :: ModuleScript).Source = source
return string.format("MTL_RoadMap: %d road rects, %d water rects, %d names, %d chars", #roads, #water, #names, #source)
