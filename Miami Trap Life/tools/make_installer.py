#!/usr/bin/env python3
"""Builds tools/Install.lua: one Luau script that writes every file in src/ into Studio (Command Bar or Studio MCP).
Rojo-style names: X.server.lua -> Script, X.client.lua -> LocalScript, X.lua -> ModuleScript, folders -> Folder.
Only touches the MTL folders. Then saves every UI/Build screen (HUD, Phone, ...) into StarterGui as real instances."""
import os, sys
root = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
out = []
out.append('-- [MTL Install] generated by tools/make_installer.py. Do not edit by hand.')
out.append('local function svc(path)\n local cur = game\n for name in string.gmatch(path, "[^/]+") do\n  local nxt = cur:FindFirstChild(name)\n  if not nxt then\n   if cur == game then nxt = game:GetService(name) else nxt = Instance.new("Folder"); nxt.Name = name; nxt.Parent = cur end\n  end\n  cur = nxt\n end\n return cur\nend')
out.append('local function put(dir, name, class, src)\n local parent = svc(dir)\n local old = parent:FindFirstChild(name)\n if old and old.ClassName ~= class then old:Destroy(); old = nil end\n local s = old or Instance.new(class)\n s.Name = name\n s.Source = src\n s.Parent = parent\nend')
count = 0
for dirpath, dirs, files in sorted(os.walk(root)):
    dirs.sort()
    rel = os.path.relpath(dirpath, root).replace(os.sep, '/')
    for f in sorted(files):
        if not f.endswith('.lua'):
            continue
        src = open(os.path.join(dirpath, f), encoding='utf-8').read()
        if f.endswith('.server.lua'): name, cls = f[:-11], 'Script'
        elif f.endswith('.client.lua'): name, cls = f[:-11], 'LocalScript'
        else: name, cls = f[:-4], 'ModuleScript'
        eq = '=' * 6
        while (']' + eq + ']') in src: eq += '='
        out.append(f'put("{rel}", "{name}", "{cls}", [{eq}[{src}]{eq}])')
        count += 1
out.append('''-- save every UI/Build/<Name> screen (MTL_HUD, MTL_Phone, ...) into StarterGui as real instances (Alex reskins them)
do
 -- require from a throwaway copy so a re-run never gets an old cached module
 local tmp = game.ReplicatedStorage.MTL:Clone()
 tmp.Name = "MTL_InstallTmp"
 tmp.Parent = game.ServerStorage
 for _, m in tmp.UI.Build:GetChildren() do
  if m:IsA("ModuleScript") then
   local ok, err = pcall(function()
    local build = require(m)
    local gui = build.build()
    local old = game.StarterGui:FindFirstChild(gui.Name)
    if old then old:Destroy() end
    gui.Parent = game.StarterGui
   end)
   print("[MTL Install] " .. m.Name .. " into StarterGui:", ok, err or "")
  end
 end
 tmp:Destroy()
end''')
out.append(f'print("[MTL Install] wrote {count} scripts")')
dst = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'Install.lua')
open(dst, 'w', encoding='utf-8').write('\n'.join(out) + '\n')
print(dst, count)
